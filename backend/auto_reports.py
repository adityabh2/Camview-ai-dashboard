"""
auto_reports.py — reports that reach clients by themselves.

* Daily report: every day at CAMVIEW_DAILY_REPORT_HOUR (local time, default 20:00) each active client gets a
  report of that day's alerts — only when the day had any. Shared in the portal and announced in-app.
* End-of-project report: the day after a registered project code's exam ends (end date from Camview's Project
  Lookup, or the exam's own end date), each client of that exam gets one full report of the whole project.

Both are built through the client firewall (reports.build_client), exactly like a report an operator shares by
hand, recorded as generated by "Automatic report", and never sent twice (the setting AUTO_DONE remembers them).
Local time = UTC + CAMVIEW_REPORT_TZ_OFFSET minutes (default 330, India).
"""

import logging
import os
import threading
import time
from datetime import datetime, timedelta, timezone

import db

log = logging.getLogger("camview.reports.auto")

AUTO_DONE = "auto_reports_done"
SYSTEM = {"id": None, "name": "Automatic report", "permissions": set(), "audience": "internal"}
CHECK_SECONDS = 300


def _settings():
    return {
        "daily": os.environ.get("CAMVIEW_AUTO_REPORT_DAILY", "1") != "0",
        "onEnd": os.environ.get("CAMVIEW_AUTO_REPORT_ON_END", "1") != "0",
        "hour": max(0, min(23, int(os.environ.get("CAMVIEW_DAILY_REPORT_HOUR", "20") or 20))),
        "offset": int(os.environ.get("CAMVIEW_REPORT_TZ_OFFSET", "330") or 330),
    }


def _local_now(offset):
    return datetime.now(timezone.utc) + timedelta(minutes=offset)


def _utc_range(day, offset):
    """Local calendar day → (start, end) as UTC ISO strings."""
    start = datetime(day.year, day.month, day.day, tzinfo=timezone.utc) - timedelta(minutes=offset)
    end = start + timedelta(days=1) - timedelta(seconds=1)
    return start.strftime("%Y-%m-%dT%H:%M:%SZ"), end.strftime("%Y-%m-%dT%H:%M:%SZ")


def _done():
    return db.get_setting(AUTO_DONE, {}) or {}


def _mark(key, rid):
    d = _done()
    d[key] = rid
    db.set_setting(AUTO_DONE, d)


def _share(client, title, filters, key):
    """Builds, saves and shares one client report. Returns the report id, or None when there was nothing in it."""
    import notify
    import reports
    rep = reports.build_client("client_shared", SYSTEM, client["id"], filters)
    if not rep["meta"]["recordCount"]:
        return None
    rep["meta"]["title"] = title
    rep["meta"]["automatic"] = True
    rid = reports.save(rep, SYSTEM, client["id"])
    db.execute("UPDATE reports SET shared_with_client=1 WHERE id=?", (rid,))
    db.audit("report.auto_share", None, "report", rid, None, title, client_id=client["id"],
             details={"key": key, "records": rep["meta"]["recordCount"]})
    notify.to_client(client["id"], "client", f"New report: {title}",
                     f"{rep['meta']['recordCount']} alert(s). Open it in Reports.", f"#/client/reports/{rid}",
                     dedupe=f"autoreport:{key}")
    return rid


def _clients():
    return db.rows("SELECT id, name, status FROM clients WHERE status='active' ORDER BY name")


def daily(now_local=None, cfg=None):
    """The day's report for every client, once the report hour has passed. Returns the number shared."""
    cfg = cfg or _settings()
    if not cfg["daily"]:
        return 0
    now_local = now_local or _local_now(cfg["offset"])
    if now_local.hour < cfg["hour"]:
        return 0
    day = now_local.date()
    start, end = _utc_range(day, cfg["offset"])
    done, n = _done(), 0
    for c in _clients():
        key = f"daily:{c['id']}:{day.isoformat()}"
        if key in done:
            continue
        rid = _share(c, f"Daily report — {day.strftime('%d %b %Y')}", {"from": start, "to": end}, key)
        _mark(key, rid)                               # also remembered when empty: never re-checked that day
        done[key] = rid
        n += bool(rid)
    return n


def _ended_projects(today):
    """[(label, project ids, end date)] for every exam / project code whose end date is before today."""
    import exams
    import project_codes
    out = []
    for e in project_codes.entries():
        end = project_codes.end_date(e["code"])
        if end and end < today.isoformat() and e.get("projectIds"):
            out.append((f"code:{e['code']}", e["code"], [str(p) for p in e["projectIds"]], end))
    for x in exams.list_exams():
        end = (x.get("endDate") or "")[:10]
        if end and end < today.isoformat() and x.get("projectIds"):
            out.append((f"exam:{x['id']}", x.get("name") or x.get("code"), [str(p) for p in x["projectIds"]], end))
    return out


def on_end(now_local=None, cfg=None):
    """One full report per client of each finished project. Returns the number shared."""
    cfg = cfg or _settings()
    if not cfg["onEnd"]:
        return 0
    today = (now_local or _local_now(cfg["offset"])).date()
    done, n = _done(), 0
    for key_base, label, pids, end in _ended_projects(today):
        clients = db.rows("SELECT DISTINCT c.id, c.name, c.status FROM clients c JOIN client_projects cp ON cp.client_id=c.id "
                          f"WHERE c.status='active' AND cp.project_id IN ({','.join('?' for _ in pids)})", pids)
        for c in clients:
            # keyed by the projects themselves: a code and an exam covering the same projects give ONE report
            key = f"end:{','.join(sorted(pids, key=str))}:{c['id']}"
            if key in done or f"end:{key_base}:{c['id']}" in done:
                continue
            rid = _share(c, f"Final report — {label} (ended {end})", {"projects": pids}, key)
            _mark(key, rid)
            done[key] = rid                           # the same run must not send it again from another source
            n += bool(rid)
    return n


def tick():
    return daily(), on_end()


_started = {"on": False}


def start():
    """Background loop (one per process). Not started in tests."""
    if _started["on"] or os.environ.get("CAMVIEW_TESTING") == "1":
        return
    _started["on"] = True

    def loop():
        time.sleep(60)
        while True:
            try:
                d, e = tick()
                if d or e:
                    log.info("Automatic reports shared: %s daily, %s end-of-project", d, e)
            except Exception:
                log.exception("Automatic reports failed")
            time.sleep(CHECK_SECONDS)
    threading.Thread(target=loop, name="auto-reports", daemon=True).start()
